{#
  dbt's built-in implementation returns default_schema ~ '_' ~ custom_schema_name,
  which would put every gold model in a schema named silver_gold.
#}
{% macro generate_schema_name(custom_schema_name, node) -%}
    {%- set default_schema = target.schema -%}
    {%- if custom_schema_name is none -%}
        {{ default_schema }}
    {%- else -%}
        {{ custom_schema_name | trim }}
    {%- endif -%}
{%- endmacro %}
